                "Demo users:\n"
                "  admin / admin12345\n"
                "  waiter / waiter12345\n"
                "  kitchen / kitchen12345\n"
                f"Categories: {restaurant.categories.count()}\n"
                f"Menu items: {restaurant.menu_items.count()}\n"
                f"Tables: {restaurant.tables.count()}\n"
                f"Table 1 QR URL: /api/public/qr/{table_one.qr_token}/menu/"
