    def create_users(self):
        user_model = get_user_model()
        users = (
            ("admin", "admin12345", user_model.Role.ADMIN, True, True),
            ("waiter", "waiter12345", user_model.Role.WAITER, False, False),
            ("kitchen", "kitchen12345", user_model.Role.KITCHEN, False, False),
        )
        for username, password, role, is_staff, is_superuser in users:
            user, _ = user_model.objects.get_or_create(username=username)
            user.role = role
            user.is_active = True
            user.is_staff = is_staff
            user.is_superuser = is_superuser
            user.set_password(password)
            user.save(update_fields=("role", "is_active", "is_staff", "is_superuser", "password"))

    def create_categories(self, restaurant):
        categories = {}
        for sort_order, (name_ky, name_ru, color) in enumerate(CATEGORIES, start=1):
            category, _ = Category.objects.update_or_create(
                restaurant=restaurant,
                name_ky=name_ky,
                defaults={
                    "name_ru": name_ru,
                    "sort_order": sort_order,
                    "is_visible": True,
                    "is_deleted": False,
                },
            )
            categories[name_ky] = (category, color)
        return categories

    def create_menu_items(self, restaurant, categories):
        for data in MENU_ITEMS:
            category, color = categories[data["category"]]
            image_path = create_demo_menu_image(data["slug"], data["name_ru"], color)
            MenuItem.objects.update_or_create(
                restaurant=restaurant,
                name_ky=data["name_ky"],
                defaults={
                    "category": category,
                    "name_ru": data["name_ru"],
                    "description_ky": data["description_ky"],
                    "description_ru": data["description_ru"],
                    "image": image_path,
                    "price": data["price"],
                    "ingredients_ky": data["ingredients_ky"],
                    "ingredients_ru": data["ingredients_ru"],
                    "allergens_ky": data["allergens_ky"],
                    "allergens_ru": data["allergens_ru"],
                    "cooking_time_min": data["cooking_time_min"],
                    "is_available": True,
                    "is_visible": True,
                    "is_deleted": False,
                },
            )
